#!/usr/bin/env python3
"""Draws the Old Man Weather mark and writes it as an LVGL 8 image array.

The geometry is taken from the approved boot artboard (Claude Design canvas
"Old Man Weather - Logo", project/Boot.dc.html), whose icon is an SVG in a 240x240
viewBox. Shapes are translated to Pillow calls here rather than rasterised from the
SVG, so this needs no SVG library -- the same approach gen_icons.py uses.

Rendered at SS x and downsampled for clean edges, directly onto the screen background
colour (the screen never changes colour; night only dims the backlight), so it is
stored as plain RGB565 with no alpha channel.

Usage:  python3 gen_logo.py            (writes ../firmware/src/icons/logo.c/.h)
Needs:  pip install pillow
"""
from pathlib import Path
from PIL import Image, ImageDraw

BG = (0xF6, 0xF3, 0xEC)       # col::BG
BLUE = (0x2B, 0x5F, 0x9E)     # col::PRESSURE / ACCENT
SUN = (0xF2, 0xB2, 0x32)
CLOUD = (0xF6, 0xF3, 0xEC)
INK = (0x1C, 0x1B, 0x19)      # col::TEXT
MOUSTACHE = (0x5A, 0x56, 0x4E)  # col::MUTED

SIZE = 320   # on-screen size, as the artboard uses
SS = 4       # supersampling factor
VB = 240.0   # the artwork's viewBox
OUT = Path(__file__).resolve().parent.parent / "firmware" / "src" / "icons"


class Pen:
    """Draws in the artwork's 240-unit space, scaled onto a supersampled canvas."""

    def __init__(self, size, ss):
        self.k = size * ss / VB
        self.img = Image.new("RGB", (size * ss, size * ss), BG)
        self.d = ImageDraw.Draw(self.img)

    def p(self, x, y):
        return (x * self.k, y * self.k)

    def box(self, x0, y0, x1, y1):
        return [self.p(x0, y0), self.p(x1, y1)]

    def rrect(self, x0, y0, x1, y1, r, fill):
        self.d.rounded_rectangle(self.box(x0, y0, x1, y1), radius=r * self.k, fill=fill)

    def disc(self, cx, cy, r, fill):
        self.d.ellipse(self.box(cx - r, cy - r, cx + r, cy + r), fill=fill)

    def ring(self, cx, cy, r, stroke, colour):
        """A circle outline, stroke centred on radius r as SVG does it."""
        outer = r + stroke / 2.0
        self.d.ellipse(self.box(cx - outer, cy - outer, cx + outer, cy + outer),
                       outline=colour, width=int(round(stroke * self.k)))

    def polyline(self, pts, stroke, colour):
        self.d.line([self.p(*q) for q in pts], fill=colour,
                    width=int(round(stroke * self.k)), joint="curve")
        # Round caps, which Pillow's line() does not provide.
        for q in (pts[0], pts[-1]):
            self.disc(q[0], q[1], stroke / 2.0, colour)

    def polygon(self, pts, fill):
        self.d.polygon([self.p(*q) for q in pts], fill=fill)

    def finish(self, size):
        return self.img.resize((size, size), Image.LANCZOS)


def cubic(p0, c0, c1, p1, steps=48):
    out = []
    for i in range(steps + 1):
        t = i / steps
        u = 1 - t
        out.append((u * u * u * p0[0] + 3 * u * u * t * c0[0] + 3 * u * t * t * c1[0] + t * t * t * p1[0],
                    u * u * u * p0[1] + 3 * u * u * t * c0[1] + 3 * u * t * t * c1[1] + t * t * t * p1[1]))
    return out


def quad(p0, c, p1, steps=24):
    out = []
    for i in range(steps + 1):
        t = i / steps
        u = 1 - t
        out.append((u * u * p0[0] + 2 * u * t * c[0] + t * t * p1[0],
                    u * u * p0[1] + 2 * u * t * c[1] + t * t * p1[1]))
    return out


def make_mark(size=SIZE):
    pen = Pen(size, SS)
    # The rounded blue tile.
    pen.rrect(0, 0, VB, VB, 54, BLUE)
    # The sun, behind the cloud.
    pen.disc(170, 74, 30, SUN)
    # The cloud: three discs over a rounded bar.
    pen.disc(84, 136, 40, CLOUD)
    pen.disc(132, 112, 50, CLOUD)
    pen.disc(176, 142, 34, CLOUD)
    pen.rrect(56, 134, 206, 186, 26, CLOUD)
    # Spectacles, stroke 6, and the bridge between them.
    pen.ring(112, 140, 15, 6, INK)
    pen.ring(150, 140, 15, 6, INK)
    pen.polyline(quad((127, 139), (131, 133), (135, 139)), 6, INK)
    # The moustache: one closed path of four cubic segments.
    path = []
    for seg in (((131, 166), (120, 155), (100, 156), (92, 170)),
                ((92, 170), (104, 170), (118, 173), (131, 167)),
                ((131, 167), (144, 173), (158, 170), (170, 170)),
                ((170, 170), (162, 156), (142, 155), (131, 166))):
        path += cubic(*seg)
    pen.polygon(path, MOUSTACHE)
    return pen.finish(size)


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def emit(images):
    OUT.mkdir(parents=True, exist_ok=True)
    c = ['// Generated by tools/gen_logo.py. Do not edit.', '#include "logo.h"', '']
    h = ['// Generated by tools/gen_logo.py. Do not edit.', '#pragma once', '#include <lvgl.h>', '']
    for sym, img in images:
        w, hgt = img.size
        data = []
        for r, g, b in img.getdata():
            v = rgb565(r, g, b)
            data += [v & 0xFF, v >> 8]  # little-endian, LV_COLOR_16_SWAP = 0
        c.append(f"static const uint8_t {sym}_map[] = {{")
        for i in range(0, len(data), 24):
            c.append("  " + ",".join(f"0x{x:02X}" for x in data[i:i + 24]) + ",")
        c.append("};")
        c.append(f"const lv_img_dsc_t {sym} = {{")
        c.append(f"  .header = {{ .cf = LV_IMG_CF_TRUE_COLOR, .always_zero = 0, .reserved = 0, .w = {w}, .h = {hgt} }},")
        c.append(f"  .data_size = {len(data)},")
        c.append(f"  .data = {sym}_map,")
        c.append("};")
        c.append("")
        h.append(f"extern const lv_img_dsc_t {sym};")
    (OUT / "logo.c").write_text("\n".join(c) + "\n")
    (OUT / "logo.h").write_text("\n".join(h) + "\n")


if __name__ == "__main__":
    mark = make_mark(SIZE)
    emit([("ic_logo_320", mark)])
    mark.save(Path(__file__).resolve().parent / "logo_preview.png")
    print(f"wrote {OUT/'logo.c'} ({SIZE}x{SIZE}, {SIZE*SIZE*2} bytes) and logo_preview.png")
